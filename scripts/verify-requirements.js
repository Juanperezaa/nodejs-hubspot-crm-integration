#!/usr/bin/env node
'use strict';

/**
 * Requirement traceability gate.
 *
 * Walks `requirements.manifest.js` and proves, for every artefact the technical
 * brief names, that it exists on disk, that its module loads, and that the
 * required export is present and of the right shape. Prints a PASS/FAIL matrix
 * grouped by brief section.
 *
 * Two modes:
 *   default    report coverage and exit 0 — used while the project is still
 *              being built, so CI stays green and the matrix stays visible
 *   --strict   exit non-zero if any artefact is missing — enabled in CI once
 *              the implementation is complete, turning the matrix into a gate
 *
 * Usage:
 *   node scripts/verify-requirements.js
 *   node scripts/verify-requirements.js --strict
 *   node scripts/verify-requirements.js --markdown > docs/REQUIREMENTS_MATRIX.md
 */

const fs = require('fs');
const path = require('path');
const { REQUIRED_ARTEFACTS } = require('./requirements.manifest');

const PROJECT_ROOT = path.resolve(__dirname, '..');

const STATUS = {
  PASS: 'PASS',
  MISSING: 'MISSING',
  LOAD_ERROR: 'LOAD_ERROR',
  EXPORT_MISSING: 'EXPORT_MISSING',
  WRONG_TYPE: 'WRONG_TYPE',
  EMPTY_MODULE: 'EMPTY_MODULE',
};

/**
 * Resolves a manifest entry to a concrete verdict.
 *
 * Loading is wrapped because a module under construction may throw at require
 * time; that is a distinct failure from the file being absent, and the two
 * deserve different messages.
 *
 * @param {{id: string, kind: string, modulePath: string, exportName?: string}} artefact
 * @returns {{status: string, detail: string}}
 */
function verifyArtefact(artefact) {
  const absolutePath = path.join(PROJECT_ROOT, artefact.modulePath);

  if (!fs.existsSync(absolutePath)) {
    return { status: STATUS.MISSING, detail: 'file does not exist' };
  }

  if (artefact.kind === 'file') {
    return { status: STATUS.PASS, detail: 'file present' };
  }

  let loadedModule;
  try {
    loadedModule = require(absolutePath);
  } catch (loadError) {
    return { status: STATUS.LOAD_ERROR, detail: loadError.message.split('\n')[0] };
  }

  if (artefact.kind === 'module') {
    const exportedKeys = Object.keys(loadedModule || {});
    if (exportedKeys.length === 0 && typeof loadedModule !== 'function') {
      return { status: STATUS.EMPTY_MODULE, detail: 'module exports nothing' };
    }
    return { status: STATUS.PASS, detail: `exports: ${exportedKeys.join(', ') || 'callable'}` };
  }

  // kind === 'function'
  const exported = loadedModule ? loadedModule[artefact.exportName] : undefined;
  if (exported === undefined) {
    const available = Object.keys(loadedModule || {}).join(', ') || 'nothing';
    return {
      status: STATUS.EXPORT_MISSING,
      detail: `no export "${artefact.exportName}" (module exports: ${available})`,
    };
  }
  if (typeof exported !== 'function') {
    return { status: STATUS.WRONG_TYPE, detail: `"${artefact.exportName}" is ${typeof exported}` };
  }
  return { status: STATUS.PASS, detail: `${artefact.exportName}(${exported.length} params)` };
}

/**
 * Groups results in the order the brief presents them, so the matrix can be
 * read side by side with the original document.
 *
 * @param {Array<object>} results
 * @returns {Map<string, Array<object>>}
 */
function groupBySection(results) {
  const grouped = new Map();
  for (const result of results) {
    if (!grouped.has(result.section)) {
      grouped.set(result.section, []);
    }
    grouped.get(result.section).push(result);
  }
  return grouped;
}

function renderConsole(results) {
  const grouped = groupBySection(results);
  const symbols = { [STATUS.PASS]: '  OK  ', default: ' FAIL ' };

  process.stdout.write('\nRequirement verification\n');
  process.stdout.write('='.repeat(78) + '\n');

  for (const [section, entries] of grouped) {
    process.stdout.write(`\n${section}\n${'-'.repeat(78)}\n`);
    for (const entry of entries) {
      const mark = entry.status === STATUS.PASS ? symbols[STATUS.PASS] : symbols.default;
      process.stdout.write(`[${mark}] ${entry.id.padEnd(5)} ${entry.modulePath}\n`);
      process.stdout.write(`          ${entry.requirement}\n`);
      if (entry.status !== STATUS.PASS) {
        process.stdout.write(`          -> ${entry.status}: ${entry.detail}\n`);
      }
    }
  }

  const passed = results.filter((entry) => entry.status === STATUS.PASS).length;
  process.stdout.write('\n' + '='.repeat(78) + '\n');
  process.stdout.write(`Coverage: ${passed} / ${results.length} artefacts verified\n\n`);
  return passed;
}

function renderMarkdown(results) {
  const grouped = groupBySection(results);
  const lines = [
    '# Requirements Matrix',
    '',
    '> Generated by `npm run verify:requirements -- --markdown`. Do not edit by hand.',
    '',
    'Each row is proven mechanically: the file is loaded and the export inspected.',
    '',
  ];

  for (const [section, entries] of grouped) {
    lines.push(
      `## ${section}`,
      '',
      '| ID | Requirement | Implementation | Status |',
      '|---|---|---|---|'
    );
    for (const entry of entries) {
      const mark = entry.status === STATUS.PASS ? 'PASS' : `FAIL — ${entry.status}`;
      lines.push(`| ${entry.id} | ${entry.requirement} | \`${entry.modulePath}\` | ${mark} |`);
    }
    lines.push('');
  }

  const passed = results.filter((entry) => entry.status === STATUS.PASS).length;
  lines.push('---', '', `**Coverage: ${passed} / ${results.length} artefacts verified.**`, '');
  process.stdout.write(lines.join('\n'));
  return passed;
}

function main() {
  const isStrict = process.argv.includes('--strict');
  const asMarkdown = process.argv.includes('--markdown');

  const results = REQUIRED_ARTEFACTS.map((artefact) => ({
    ...artefact,
    ...verifyArtefact(artefact),
  }));

  const passed = asMarkdown ? renderMarkdown(results) : renderConsole(results);
  const failed = results.length - passed;

  if (failed > 0 && isStrict) {
    process.stderr.write(`Strict mode: ${failed} artefact(s) missing or invalid.\n`);
    process.exit(1);
  }
  process.exit(0);
}

main();
